def graphic(dest:Path,kind:int):
    w,h=960,540
    im=Image.new("RGB",(w,h))
    p=im.load()
    palettes=[
        ((13,47,51),(41,119,101)),
        ((15,38,56),(63,90,109)),
        ((11,28,49),(28,73,91))
    ]
    dark,bright=palettes[kind]
    for y in range(h):
        z=y/h
        for x in range(w):
            p[x,y]=tuple(round(dark[i]*(1-z)+bright[i]*z) for i in range(3))
    d=ImageDraw.Draw(im,"RGBA")
    rng=random.Random(71001+kind*19)
    for _ in range(170):
        x,y=rng.randrange(w),rng.randrange(h)
        r=rng.randrange(1,4)
        d.ellipse((x-r,y-r,x+r,y+r),fill=(215,229,190,rng.randrange(25,75)))
    if kind<2:
        layers=[(305,(89,144,100,235)),(360,(99,98,58,240)),(425,(119,88,56,240))]
        for top,color in layers:
            pts=[(0,top)]
            pts.extend((x,top+int(math.sin(x*.011+kind)*8)+int(math.cos(x*.029)*4)) for x in range(0,w+1,12))
            pts += [(w,h),(0,h)]
            d.polygon(pts,fill=color)
        for k in range(10):
            x=70+84*k
            d.arc((x,180+30*(k%3),x+50,225+30*(k%3)),190,350,fill=(140,241,222,180),width=4)
            d.ellipse((x+12,320+24*(k%4),x+29,343+24*(k%4)),fill=(98,204,224,230))
        # physical measurement vertical indicator and stratified levels
        d.rounded_rectangle((115,65,180,450),20,fill=(18,45,50,200),outline=(250,203,112,230),width=5)
        d.rectangle((138,170,158,380),fill=(73,195,214,210))
        d.ellipse((125,364,172,414),fill=(90,209,228,250))
        for y in range(150,380,33):
            d.line((164,y,185,y),fill=(255,224,153,200),width=3)
    else:
        for i,c in enumerate(((251,201,103,255),(117,235,220,255),(188,169,252,255))):
            xc=170+310*i
            d.rounded_rectangle((xc-85,310,xc+85,486),25,fill=(18,53,56,220),outline=c,width=10)
            for j in range(4):
                x=xc+int(math.sin((j+i)*3)*65)
                y=85+j*48
                d.ellipse((x-24,y-29,x+24,y+29),fill=c,outline=(255,255,255,160),width=2)
