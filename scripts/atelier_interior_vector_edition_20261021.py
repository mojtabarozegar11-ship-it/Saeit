def build_from_original(raw):
    if sha(raw)!=OLD_SHA:
        raise RuntimeError("ORIGINAL_ARCHIVE_SHA_MISMATCH")
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        if z.testzip() is not None or len(z.namelist())!=11:
            raise RuntimeError("UNSAFE_ORIGINAL_PACKAGE")
        if set(z.namelist())!=set(TEXT_NAMES)|{"assets/"+n+".jpg" for n in IMAGE_NAMES}:
            raise RuntimeError("UNEXPECTED_ORIGINAL_ZIP_MEMBERS")
        out={}
        for name in TEXT_NAMES:
            txt=z.read(name).decode("utf8")
            txt=txt.replace(".jpg",".svg")
            if name=="README.md":
                txt+=LICENSE_APPEND
            if re.search(r"https?://(?!wa[.]me|www[.]w3[.]org)",txt):
                # Existing demo source contains no remote assets: preserve offline standalone use.
                raise RuntimeError("UNEXPECTED_REMOTE_ASSET_OR_LINK:"+name)
            out[name]=txt.encode("utf8")
        for i,name in enumerate(IMAGE_NAMES):
            out["assets/"+name+".svg"]=svg_scene(i)
    if b"ATELIER_CONFIG" not in out["config.js"]:
        raise RuntimeError("CONFIG_MISSING")
    if b".jpg" in b"".join(out[n] for n in TEXT_NAMES):
        raise RuntimeError("UNREPLACED_PHOTO_REFERENCES")
    data=io.BytesIO()
    with zipfile.ZipFile(data,"w",compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for name,blob in out.items():
            info=zipfile.ZipInfo(name,(2026,10,21,18,20,0))
            info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=(0o100644<<16)
            z.writestr(info,blob,compress_type=zipfile.ZIP_DEFLATED,compresslevel=9)
    result=data.getvalue()
    with zipfile.ZipFile(io.BytesIO(result)) as z:
        if z.testzip() is not None or set(z.namelist())!=set(out):
            raise RuntimeError("UNSAFE_NEW_ARCHIVE")
        if any(z.read("assets/"+n+".svg")!=out["assets/"+n+".svg"] for n in IMAGE_NAMES):
            raise RuntimeError("VECTOR_ASSET_BROKEN")
    if len(result)>10_000_000:
        raise RuntimeError("UNEXPECTED_ARCHIVE_SIZE")
    return result

