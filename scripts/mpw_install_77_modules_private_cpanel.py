"""Atomic install + real canary of all 77 original modules, only in MPW private space.

Input: the SHA-manifest tar generated by pinned CI, with two members
runner.py and manifest.json. All existing workers, crons, website and sibling
sites are unaffected on any failure. Only one new private hourly Cron is added
after all 77 imports complete successfully in a read-only child.
"""
import fcntl
import getpass
import hashlib
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import tarfile
import tempfile

TENANT="mojplaywin-main"
ROOT=Path("/home/zomorod2/.private_mojplaywin_main_agents")
STAGE=ROOT/"v91_verified_main_port_20261018"
EVO=ROOT/"evolution_runtime_20261018"
SCRIPTS=STAGE/"scripts"
DEST=SCRIPTS/"mpw_77_modules_private_runner.py"
ORIGIN=STAGE/"mpw_v91_port/ORIGIN.json"
EVOLUTION_MARK="MPW_PRIVATE_EVOLUTION_MAIN_ONLY_20261018"
CRON_MARK="MPW_77_MODULES_MAIN_ONLY_20261018"

def ensure(ok,reason):
    if not ok:raise RuntimeError(reason)

def private(path):
    return path.is_dir() and not path.is_symlink() and not (path.stat().st_mode & 0o077)

def payload():
    raw=sys.stdin.buffer.read(40001)
    ensure(0<len(raw)<=40000,"MODULE_PACKAGE_EXCEEDS_SIZE")
    with tarfile.open(fileobj=io.BytesIO(raw),mode="r:gz") as tar:
        names=tar.getnames()
        ensure(len(names)==2 and set(names)=={"runner.py","manifest.json"},"MODULE_TAR_MEMBERS_UNEXPECTED")
        for part in tar.getmembers():
            ensure(part.isfile() and part.size<23000,"MODULE_ARCHIVE_MEMBER_INVALID")
        runner=tar.extractfile("runner.py").read()
        manifest=json.load(tar.extractfile("manifest.json"))
    ensure(manifest.get("tenant")==TENANT
           and manifest.get("scope")=="mpw_existing_77_original_modules_readonly_import"
           and manifest.get("runner_sha256")==hashlib.sha256(runner).hexdigest()
           and len(runner)>8000,"MODULE_RUNNER_SOURCE_PROVENANCE_INVALID")
    compile(runner,"runner.py","exec")
    return runner

def atomic_write(path,data):
    ensure(not path.is_symlink(),"MODULE_DESTINATION_SYMLINK")
    fd,tmp=tempfile.mkstemp(prefix=".mpw-77-",dir=str(path.parent))
    try:
        os.fchmod(fd,0o600)
        with os.fdopen(fd,"wb") as out:
            out.write(data);out.flush();os.fsync(out.fileno())
        os.replace(tmp,path)
    finally:
        if os.path.lexists(tmp):os.unlink(tmp)

def run_agent(flags):
    p=subprocess.run(["/usr/bin/python3","-B",str(DEST),flags],capture_output=True,text=True,timeout=80)
    ensure(p.returncode==0,"MODULE_ACTIVATION_FAILED:"+flags+":"+p.stderr[-1700:])
    try:
        val=json.loads(p.stdout.splitlines()[-1])
    except Exception as e:
        raise RuntimeError("UNRECOGNIZED_MODULE_ACTIVATION_OUTPUT") from e
    return val

def main():
    os.umask(0o077)
    ensure(getpass.getuser()=="zomorod2","INVALID_CPANEL_USER")
    code=payload()
    ensure(all(private(p) for p in (ROOT,STAGE,EVO,SCRIPTS,STAGE/"mpw_v91_port",
                                    STAGE/"operator_state")),"PRIVATE_ORIGINAL_MODULE_STAGE_INVALID")
    enable=STAGE/"operator_state/enabled"
    ensure(enable.is_file() and not enable.is_symlink()
           and enable.read_text().strip()=="MPW_V91_MAIN_ONLY_PRIVATE_20261018",
           "MISSING_OWNER_MAIN_SITE_ACTIVATION")
    ensure(ORIGIN.is_file() and not ORIGIN.is_symlink()
           and json.loads(ORIGIN.read_text())["file_count"]==77,
           "ORIGINAL_77_MODULE_MANIFEST_MISSING")
    cron_before=subprocess.run(["crontab","-l"],capture_output=True,text=True,check=True,timeout=15).stdout
    ensure(sum(EVOLUTION_MARK in x for x in cron_before.splitlines())==1,
           "MAIN_GEN65_EVOLUTION_NOT_SCHEDULED")
    # Safe in-place upgrade of an already operational private 77-module
    # heartbeat: only the exact previously installed task is accepted.
    existing=[row for row in cron_before.splitlines() if CRON_MARK in row]
    approved=("43 * * * * /usr/bin/flock -n "+str(EVO/"modules77.cron.lock")
         +" /usr/bin/python3 -B "+str(DEST)
         +" --once > "+str(EVO/"modules77.last.log")
         +" 2>&1 # "+CRON_MARK)
    ensure(not existing or existing==[approved],
           "MODULE_77_CRON_OWNERSHIP_OR_SCHEDULE_CONFLICT")
    ensure(not DEST.is_symlink(),"MODULE_SOURCE_SYMLINK")
    previous=DEST.read_bytes() if DEST.is_file() else None
    fd=os.open(str(EVO/"modules77.install.lock"),os.O_CREAT|os.O_RDWR|
               getattr(os,"O_NOFOLLOW",0),0o600)
    try:
        fcntl.flock(fd,fcntl.LOCK_EX)
        ensure(subprocess.run(["crontab","-l"],capture_output=True,text=True,check=True,timeout=15).stdout==cron_before,
               "CRON_CHANGED_DURING_VERIFICATION")
        try:
            atomic_write(DEST,code)
            ensure(hashlib.sha256(DEST.read_bytes()).hexdigest()==hashlib.sha256(code).hexdigest(),
                   "PRIVATE_77_RUNNER_INSTALL_MISMATCH")
            result=run_agent("--once")
            ensure(result.get("verified")==77
                   and result.get("imported")==77
                   and result.get("status")=="77_verified_original_modules_exercised_privately"
                   and result.get("capability_namespaces_active")==77
                   and result.get("functional_probes_executed")>=14,
                   "NOT_ALL_77_IMPORTED_IN_CPANEL")
            result_cron=run_agent("--install-cron")
            ensure(result_cron.get("status") in ("77_module_hourly_health_job_enabled",
                                                "77_module_hourly_job_already_active"),
                   "MODULE_CRON_NOT_INSTALLED")
            cron_after=subprocess.run(["crontab","-l"],capture_output=True,text=True,check=True,timeout=15).stdout
            ensure(len([r for r in cron_after.splitlines() if CRON_MARK in r])==1
                   and all(r in cron_after.splitlines() for r in cron_before.splitlines()),
                   "EXISTING_AGENT_CRONS_CHANGED")
            report_path=EVO/"all_77_modules_last_run.json"
            report=json.loads(report_path.read_text())
            ensure(report["modules_import_executed"]==77
                   and report["modules_hash_verified"]==77
                   and report["capability_namespaces_active"]==77
                   and report["functional_probes_executed"]>=14
                   and len(report["per_module_capability_registry"])==77
                   and report["financial_authority"] is False
                   and report["public_site_modified"] is False,
                   "PRIVATE_77_EXECUTION_READBACK_FAILED")
            print(json.dumps({
                 "status":"ALL_77_ORIGINAL_MODULES_IMPORTED_AND_EXERCISED_ON_CPANEL",
                 "module_count":77,"successful_imports":77,
                 "pure_contract_checks":result["pure_probes"],
                 "capability_namespaces_active":77,
                 "functional_contracts_exercised":result["functional_probes_executed"],
                 "source_sha256":hashlib.sha256(code).hexdigest(),
                 "schedule":"43 * * * *",
                 "gen64_and_gen65_crons_preserved":True,
                 "all_old_cron_entries_preserved":True,
                 "no_new_long_lived_processes":True,
                 "other_subsites_modified":False,
                 "public_site_modified":False,
                 "transactions_executed":0},sort_keys=True))
        except BaseException:
            # Code installation is the only source operation: restore exact old
            # private source bytes and leave every external source untouched.
            if previous is None:
                if DEST.is_file() and not DEST.is_symlink(): DEST.unlink()
            else:atomic_write(DEST,previous)
            raise
    finally:
        os.close(fd)

if __name__=="__main__":main()
