"""Owner-held existing LiteFinance trading account: B-owned policy regressions."""
from dataclasses import FrozenInstanceError
import unittest
from prop_firm.plan1_owner_held_litefinance_policy import (
    FA, EN, VERSION, REVIEW_GATES, owner_held_real_account_policy,
    review_existing_broker_trading_mechanism,
)


class ExistingOwnerBrokerAccountPolicyTests(unittest.TestCase):
    def setUp(self):
        self.p=owner_held_real_account_policy()

    def test_canonical_plan1(self):
        self.assertEqual(self.p.sku,"MOJ-PROP-01")

    def test_broker_is_litefinance(self):
        self.assertEqual(self.p.broker,"LiteFinance")

    def test_owner_declared_existing_account_not_independently_proven(self):
        self.assertTrue(self.p.existing_broker_account_owner_declared)
        self.assertFalse(self.p.broker_balance_independently_verified)

    def test_broker_delegated_trading_not_assumed_authorized(self):
        self.assertFalse(self.p.broker_delegation_independently_authorized)

    def test_buyer_does_not_receive_principal(self):
        self.assertFalse(self.p.buyer_owns_or_receives_principal)

    def test_no_owner_login_password_or_2fa(self):
        self.assertFalse(self.p.buyer_gets_account_password_or_2fa)

    def test_no_direct_owner_account_withdrawal_permission(self):
        self.assertFalse(self.p.buyer_gets_broker_withdrawal_authority)

    def test_no_broker_withdrawal_directly_into_buyer_wallet(self):
        self.assertFalse(self.p.broker_directly_pays_buyer_wallet)

    def test_separate_business_treasury_payout_intended(self):
        self.assertTrue(self.p.crypto_transfer_from_separate_treasury_only)

    def test_live_only_after_two_demo_passes(self):
        self.assertTrue(self.p.live_trading_only_after_both_demo_passes)

    def test_no_realized_profit_means_no_payout(self):
        self.assertFalse(self.p.payout_without_realized_eligible_profit)

    def test_social_post_never_required(self):
        self.assertFalse(self.p.marketing_or_social_post_required)

    def test_no_autogenerated_customer_contract(self):
        self.assertFalse(self.p.buyer_contract_signed_by_this_code)

    def test_no_invoice_by_policy(self):
        self.assertFalse(self.p.invoice_issued_by_this_code)

    def test_no_real_trade_enabled_by_policy(self):
        self.assertFalse(self.p.trading_enabled_by_this_code)

    def test_no_crypto_transfer_enabled_by_policy(self):
        self.assertFalse(self.p.payout_enabled_by_this_code)

    def test_legal_broker_approval_mentioned_in_farsi(self):
        self.assertIn("مجوز رسمی کارگزار",self.p.fa)

    def test_buyer_no_usd100_deposit_in_farsi(self):
        self.assertIn("هیچ سرمایه‌ای",self.p.fa)

    def test_farsi_payout_is_after_contractual_period(self):
        self.assertIn("پایان هر دوره قراردادی",self.p.fa)

    def test_english_crypto_transfer_is_separate_from_broker(self):
        self.assertIn("separate legal business-treasury transfer",self.p.en)

    def test_net_realized_profit_and_loss_carry_disclosed(self):
        self.assertIn("REALIZED net trading profit",self.p.en)
        self.assertIn("loss carryforward",self.p.en)

    def test_crypto_fee_only_actual_and_once(self):
        self.assertIn("deducted once",self.p.en)
        self.assertIn("documented",self.p.en)

    def test_numerical_profit_share_is_70_30(self):
        self.assertIn("70% trader / 30% organizer",self.p.en)

    def test_owner_declaration_is_not_broker_confirmation(self):
        self.assertFalse(self.p.broker_delegation_independently_authorized)

    def test_policy_has_immutable_digest(self):
        self.assertEqual(len(self.p.digest_sha256),64)
        self.assertEqual(self.p.digest_sha256,owner_held_real_account_policy().digest_sha256)

    def test_policy_result_frozen(self):
        with self.assertRaises(FrozenInstanceError):
            self.p.trading_enabled_by_this_code=True

    def test_review_requires_exact_independent_evidence_set(self):
        with self.assertRaises(ValueError):
            review_existing_broker_trading_mechanism(trusted_evidence={})

    def test_review_requires_dict_not_browser_list(self):
        with self.assertRaises(ValueError):
            review_existing_broker_trading_mechanism(trusted_evidence=[])

    def test_review_rejects_each_false_broker_and_treasury_fact(self):
        for gate in REVIEW_GATES:
            with self.subTest(gate=gate):
                facts=dict.fromkeys(REVIEW_GATES,True)
                facts[gate]=False
                decision=review_existing_broker_trading_mechanism(trusted_evidence=facts)
                self.assertFalse(decision.eligible_for_independent_broker_review)
                self.assertIn(gate,decision.missing)

    def test_integer_truthiness_does_not_grant_broker_delegation(self):
        facts=dict.fromkeys(REVIEW_GATES,True)
        facts["broker_explicitly_authorized_delegated_order_mechanism"]=1
        self.assertFalse(review_existing_broker_trading_mechanism(
            trusted_evidence=facts).eligible_for_independent_broker_review)

    def test_no_owner_credentials_gate_blocks(self):
        facts=dict.fromkeys(REVIEW_GATES,True)
        facts["no_owner_password_2fa_or_withdrawal_access_to_trader"]=False
        self.assertIn("no_owner_password_2fa_or_withdrawal_access_to_trader",
                      review_existing_broker_trading_mechanism(
                          trusted_evidence=facts).missing)

    def test_all_true_only_allows_independent_review_not_trading(self):
        facts=dict.fromkeys(REVIEW_GATES,True)
        decision=review_existing_broker_trading_mechanism(trusted_evidence=facts)
        self.assertTrue(decision.eligible_for_independent_broker_review)
        self.assertFalse(decision.trading_enabled)
        self.assertFalse(decision.broker_permission_proved_by_this_code)

    def test_all_true_still_does_not_enable_payout(self):
        facts=dict.fromkeys(REVIEW_GATES,True)
        decision=review_existing_broker_trading_mechanism(trusted_evidence=facts)
        self.assertFalse(decision.payout_enabled)

    def test_malicious_extra_broker_claim_rejected(self):
        facts=dict.fromkeys(REVIEW_GATES,True)
        facts["broker_owner_password_given"]=True
        with self.assertRaises(ValueError):
            review_existing_broker_trading_mechanism(trusted_evidence=facts)
