// Keyboard commands are only gameplay inputs while the arena owns focus.
// Menu buttons must retain native Enter/Space behavior for keyboard and assistive users.
export function isInteractiveTarget(target) {
  return Boolean(target && typeof target.closest === 'function' &&
    target.closest('button, a, input, textarea, select, summary, [contenteditable], [role="button"], [role="textbox"]'));
}

const COMMANDS = Object.freeze({
  KeyQ: 'rocket',
  KeyE: 'drone',
  KeyF: 'special',
  KeyR: 'reload',
  KeyG: 'interact'
});

export function keyboardAction(code, screen, target, repeat = false) {
  if (screen !== 'game' || isInteractiveTarget(target)) return null;
  if (repeat && code !== 'Space') return null;
  if (code === 'Escape') return 'pause';
  if (code === 'Space') return 'fire';
  return Object.hasOwn(COMMANDS, code) ? COMMANDS[code] : null;
}

// Map screen-space touch directions to the same movement axes as WASD:
// up = forward (W), right = strafe right (D). Clamp diagonal input so
// dragging beyond the pad never increases player speed.
export function joystickAxes(dx, dy, limit) {
  if (![dx, dy, limit].every(Number.isFinite) || limit <= 0) return {forward: 0, side: 0};
  const distance = Math.hypot(dx, dy);
  if (distance === 0) return {forward: 0, side: 0};
  const scale = Math.min(1, limit / distance) / limit;
  return {forward: -dy * scale, side: dx * scale};
}

// Ignore secondary mouse buttons and pen barrel presses on gameplay controls.
// Do not require isPrimary: a second finger must still be able to fire while moving.
export function isPrimaryGameplayPress(event) {
  return Boolean(event && event.button === 0);
}

// Native button click events generated by Enter/Space or assistive technology have detail=0.
// Pointer activation already runs on pointerdown; ignore its later click to avoid double spending.
export function isKeyboardOrAssistiveClick(event) {
  return Boolean(event && event.detail === 0);
}

// Moving focus onto a HUD/menu control must release held WASD/Space.
// Browsers may swallow keyup during keyboard or assistive focus transitions.
export function shouldReleaseHeldKeysOnFocus(screen, target) {
  return screen === 'game' && isInteractiveTarget(target);
}

// A second touch must not steal a joystick or camera pointer already in use.
// Do not require isPrimary: players must be able to move and aim with two fingers.
export function canCaptureGameplayPointer(activePointerId, incomingPointerId, screen) {
  return screen === 'game' && activePointerId === null &&
    Number.isInteger(incomingPointerId) && incomingPointerId >= 0;
}

// A different finger's pointerup/cancel must never release a held control.
export function isOwnedGameplayPointer(activePointerId, incomingPointerId) {
  return Number.isInteger(activePointerId) && activePointerId >= 0 &&
    activePointerId === incomingPointerId;
}

// Browser/system shortcuts and IME composition are never gameplay commands.
// This also protects movement keys from being latched during Ctrl/Alt/Meta combos.
export function isModifiedOrComposingKey(event) {
  return Boolean(event && (event.ctrlKey || event.altKey || event.metaKey ||
    event.isComposing || event.keyCode === 229));
}

// Normalize combined WASD and touch input to a unit vector. Without this,
// pressing W+D covers sqrt(2) times the distance of W alone per frame.
export function normalizeMovementAxes(forward, side) {
  if (!Number.isFinite(forward) || !Number.isFinite(side)) return {forward: 0, side: 0};
  const f = Math.max(-1, Math.min(1, forward));
  const s = Math.max(-1, Math.min(1, side));
  const length = Math.hypot(f, s);
  const factor = length > 1 ? 1 / length : 1;
  return {forward: f * factor, side: s * factor};
}


// A browser may coalesce pointermove events or deliver none before pointerup.
// Include release coordinates so a long aim drag cannot masquerade as a click.
export function recordPointerGestureMovement(gesture, event) {
  if (!gesture) return;
  if (![gesture.startX, gesture.startY, event?.clientX, event?.clientY].every(Number.isFinite)) {
    gesture.moved = Infinity; // Unknown release coordinates never authorize firing.
    return;
  }
  gesture.moved = Math.max(gesture.moved || 0,
    Math.hypot(event.clientX - gesture.startX, event.clientY - gesture.startY));
}

// Only an actual primary desktop mouse click may fire from the 3D canvas.
// Touch/pencil aiming on wide screens and mouse drags must not consume ammo.
export function shouldFireCanvasClick(event, screen, viewportWidth, gesture) {
  return screen === 'game' && Number.isFinite(viewportWidth) && viewportWidth >= 700 &&
    gesture?.pointerType === 'mouse' && gesture.finished === true &&
    gesture.cancelled !== true && Number.isFinite(gesture.moved) && gesture.moved <= 8 &&
    event?.button === 0 && event.detail > 0 &&
    (event.pointerType === undefined || event.pointerType === 'mouse');
}

// Keyboard and touch can hold fire concurrently. Releasing one source must not
// cancel the other; a stale/invalid pointer id must never keep firing.
export function isFireHeld(spaceKeyDown, activeFirePointerId) {
  return spaceKeyDown === true || (Number.isInteger(activeFirePointerId) && activeFirePointerId >= 0);
}

// Opposing keyboard directions cancel instead of assigning arbitrary priority.
// Touch and keyboard vectors combine before unit-speed normalization.
export function resolveMovementAxes(joyForward, joySide, keys = {}) {
  const f = (Number.isFinite(joyForward) ? joyForward : 0) +
    (keys.KeyW || keys.ArrowUp ? 1 : 0) - (keys.KeyS || keys.ArrowDown ? 1 : 0);
  const s = (Number.isFinite(joySide) ? joySide : 0) +
    (keys.KeyD || keys.ArrowRight ? 1 : 0) - (keys.KeyA || keys.ArrowLeft ? 1 : 0);
  return normalizeMovementAxes(f, s);
}
