// Keyboard commands are only gameplay inputs while the arena owns focus.
// Menu buttons must retain native Enter/Space behavior for keyboard and assistive users.
export function isInteractiveTarget(target) {
  return Boolean(target && typeof target.closest === 'function' &&
    target.closest('button, a, input, textarea, select, summary, [contenteditable], [role="button"], [role="textbox"]'));
}

const COMMANDS = Object.freeze({
  KeyQ: 'rocket',
  KeyE: 'drone',
  KeyF: 'special',
  KeyR: 'reload',
  KeyG: 'interact'
});

export function keyboardAction(code, screen, target, repeat = false) {
  if (screen !== 'game' || isInteractiveTarget(target)) return null;
  if (repeat && code !== 'Space') return null;
  if (code === 'Escape') return 'pause';
  if (code === 'Space') return 'fire';
  return Object.hasOwn(COMMANDS, code) ? COMMANDS[code] : null;
}

// Map screen-space touch directions to the same movement axes as WASD:
// up = forward (W), right = strafe right (D). Clamp diagonal input so
// dragging beyond the pad never increases player speed.
export function joystickAxes(dx, dy, limit) {
  if (![dx, dy, limit].every(Number.isFinite) || limit <= 0) return {forward: 0, side: 0};
  const distance = Math.hypot(dx, dy);
  if (distance === 0) return {forward: 0, side: 0};
  const scale = Math.min(1, limit / distance) / limit;
  return {forward: -dy * scale, side: dx * scale};
}

// Native button click events generated by Enter/Space or assistive technology have detail=0.
// Pointer activation already runs on pointerdown; ignore its later click to avoid double spending.
export function isKeyboardOrAssistiveClick(event) {
  return Boolean(event && event.detail === 0);
}

// A second touch must not steal a joystick or camera pointer already in use.
// Do not require isPrimary: players must be able to move and aim with two fingers.
export function canCaptureGameplayPointer(activePointerId, incomingPointerId, screen) {
  return screen === 'game' && activePointerId === null &&
    Number.isInteger(incomingPointerId) && incomingPointerId >= 0;
}

// A different finger's pointerup/cancel must never release a held control.
export function isOwnedGameplayPointer(activePointerId, incomingPointerId) {
  return Number.isInteger(activePointerId) && activePointerId >= 0 &&
    activePointerId === incomingPointerId;
}

// Browser/system shortcuts and IME composition are never gameplay commands.
// This also protects movement keys from being latched during Ctrl/Alt/Meta combos.
export function isModifiedOrComposingKey(event) {
  return Boolean(event && (event.ctrlKey || event.altKey || event.metaKey ||
    event.isComposing || event.keyCode === 229));
}
