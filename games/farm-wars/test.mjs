// Offline, dependency-free game mechanics regression suite.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const match=source.match(/<script>\s*([\s\S]*?)\s*<\/script>/);
assert(match,'Game JavaScript must exist');
new vm.Script(match[1],{filename:'farm-wars.js'});
const selectors={};
const buttonActs=['wheat','corn','harvest','orchard','tower','market','train','attack','repair','next','help','restart'];
function makeNode(){return {innerHTML:'',textContent:'',style:{},disabled:false,addEventListener(){},classList:{add(){},remove(){}},hasAttribute(){return false;},getAttribute(){return null;},focus(){}};}
const nodes=new Map();
for(const id of ['stats','turnInfo','farm','selection','journal','quest','enemyprogress','overlay','modalTitle','modalMessage','modalClose','sound'])nodes.set(id,makeNode());
buttonActs.forEach(a=>{const b=makeNode();b.getAttribute=()=>a;selectors[a]=b;});
let db={};
const ctx={console,Math,JSON,Number,Array,Object,Map,Set,document:{getElementById:id=>{assert(nodes.has(id),'Missing element '+id);return nodes.get(id);},querySelectorAll:q=>q==='[data-act]'?Object.values(selectors):[],addEventListener(){},activeElement:makeNode()},localStorage:{getItem:k=>db[k]??null,setItem:(k,v)=>{db[k]=v;}},window:{confirm:()=>true},};
ctx.window.window=ctx.window;
vm.createContext(ctx);vm.runInContext(match[1],ctx,{timeout:2000});
const api=ctx.window.ZomorodFarmWarsTest;
assert(api,'Test hook missing');
let s=api.getState();
assert.equal(s.tiles.length,48);
assert.equal(s.gold,160);
assert.equal(s.enemy,165);
assert.equal(s.life,130);
assert.equal(s.army,3);
assert.equal(s.tiles.filter(x=>x.type==='enemy').length,12);
assert(api.valid(s));
api.select(6);api.action('wheat');assert.equal(api.getState().tiles[6].type,'enemy','Enemy tiles must be protected');
api.select(0);api.action('wheat');s=api.getState();assert.equal(s.tiles[0].type,'wheat');assert.equal(s.gold,150);
api.action('harvest');assert.equal(api.getState().tiles[0].type,'wheat','Unripe crops cannot be harvested');
api.action('next');api.action('next');s=api.getState();assert.equal(s.tiles[0].age,2);assert(s.life<130);
api.action('harvest');s=api.getState();assert.equal(s.tiles[0].type,'empty');assert(s.food>48);
api.select(1);api.action('tower');assert.equal(api.getState().tiles[1].type,'tower');
api.select(2);api.action('orchard');assert.equal(api.getState().tiles[2].type,'orchard');
api.action('next');assert(api.getState().wood>0);
api.action('train');assert(api.getState().army>=6);
const before=api.getState().enemy;api.action('attack');assert(api.getState().enemy<before);
const gold=api.getState().gold;api.action('repair');assert(api.getState().life>=0);assert(api.getState().gold<=gold);
api.select(46);api.action('market');assert.equal(api.getState().tiles[46].type,'enemy');
const serialized=JSON.parse(db['zm-farmwars-v1-save']);assert.equal(serialized.day,4);
api.reset();s=api.getState();assert.equal(s.gold,160);assert.equal(s.done,false);
for(let i=0;i<30&&!api.getState().done;i++){api.action('attack');api.action('train');api.action('next');}
assert(api.getState().day>=1,'Turn loop must be bounded and safe');
assert(source.includes('prefers-reduced-motion'),'Reduced motion support missing');
assert(source.includes('aria-live'),'Accessible status announcements missing');
assert(!source.includes('OPENAI_API_KEY'),'No secrets in browser code');
assert(!source.includes('http://'),'No insecure external dependencies');
console.log('FARM_WARS_TESTS=PASS assertions=29');
